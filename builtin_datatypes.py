# 4 Main Collections in Python

# 1. LIST 
my_list = [1, 2, 3, 2]
my_list.append(4)
print(my_list) 



# 2. TUPLE 
my_tuple = (1, 2, 3, 2)
print(my_tuple[0]) 



# 3. SET  
my_set = {1, 2, 3, 2, 2}
print(my_set) 



# 4. DICTIONARY 
my_dict = {"name": "Shrutika",
            "lang": "Python"}
print(my_dict["name"]) 